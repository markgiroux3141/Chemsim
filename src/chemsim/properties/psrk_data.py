# ---------------------------------------------------------------------------
# Pattern corrections
# ---------------------------------------------------------------------------
# Same discipline as unifac_data: R, Q and a_mn are measurements and are
# transcribed verbatim; a SMARTS is an encoding of a definition and can be wrong.
#
# The conventional pattern for molecular hydrogen is '[HH]', which does not mean
# what it looks like. Inside brackets RDKit reads a bare H as the hydrogen-COUNT
# primitive, not the element, so '[HH]' matches any atom carrying exactly one
# hydrogen -- an alcohol's oxygen, every aromatic CH. Published at priority 1e9
# it is tried first against every molecule, so with it in the table ethanol
# fragments as CH3 + CH2 + H2 and benzoic acid loses its whole ring. '[#1][#1]'
# is the pattern that actually means two hydrogen atoms bonded together.
_SMARTS_CORRECTIONS: dict[int, tuple[str, ...]] = {
    1113: ("[#1][#1]",),      # H2
    1120: ("[2#1][2#1]",),    # D2
}

CORRECTED_GROUP_IDS: frozenset[int] = frozenset(_SMARTS_CORRECTIONS)


def _build(row: tuple) -> UnifacGroup:
    g = UnifacGroup(*row)
    smarts = _SMARTS_CORRECTIONS.get(g.group_id)
    if smarts is None:
        return g
    return UnifacGroup(
        g.group_id, g.name, g.main_group_id, g.main_group, g.R, g.Q,
        smarts, g.priority, g.atoms,
    )


