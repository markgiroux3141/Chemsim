"""PSRK gas-group extension to the UNIFAC parameter table.

Source: Holderbaum, T. & Gmehling, J. (1991), "PSRK: a group contribution
equation of state based on UNIFAC", Fluid Phase Equilib. 70, 251; parameters as
revised by Horstmann et al. and published by DDBST. Transcribed via the `thermo`
package's tabulation and re-verified against it entry-by-entry in the test suite,
exactly as the Joback and UNIFAC tables are.

WHY A SECOND TABLE EXISTS. Standard UNIFAC has no group for a permanent gas --
no O2, no N2, no CO2 -- so a dissolved gas has no activity coefficient at all,
and gas solubility could only ever be the tabulated aqueous number. PSRK is the
extension that adds them, and it is the standard one.

WHY THIS IS AN EXTENSION AND NOT A REPLACEMENT. PSRK re-regressed some of
UNIFAC's organic parameters, so adopting it wholesale would silently move results
that are already validated (the ethanol/water azeotrope, benzoic acid solubility)
and would LOSE the 96 pairs that PSRK does not carry. Instead this module supplies
ONLY the main groups UNIFAC does not have, and only the pairs involving them.
Every parameter in the merged table therefore comes from exactly one regression,
and no UNIFAC value is ever overwritten. The join is sound because PSRK's organic
backbone is UNIFAC's -- 1124 of UNIFAC's 1174 pairs are bit-identical in PSRK --
so these gas parameters were regressed against the same organic parameters we
already use.

IDS ARE OFFSET BY 1000. PSRK subgroups 118/119 (CH4, O2) collide with UNIFAC
118/119 (the sulfone groups). Offsetting both subgroup and main-group ids by a
constant makes the two numbering schemes impossible to confuse; ``PSRK_ID``
records the mapping so the oracle test can check against the original table.

INTERACTIONS ARE QUADRATIC IN TEMPERATURE: a_mn(T) = a + b*T + c*T^2. That is
PSRK's form, and 78 of the gas/solvent pairs genuinely use it -- treating them as
constants would be wrong, not merely approximate. UNIFAC's own parameters are
the b = c = 0 case, so one array covers both tables.
"""

